namespace Workable;

/// <summary>
/// Represents the direction of a query sort.
/// </summary>
public enum WorkCriteriaSortDirection
{
    /// <summary>
    /// Sort from lowest to highest or oldest to newest.
    /// </summary>
    Ascending,

    /// <summary>
    /// Sort from highest to lowest or newest to oldest.
    /// </summary>
    Descending,
}
