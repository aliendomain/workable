namespace Workable;

/// <summary>
/// Represents the declared risk level of a work definition.
/// </summary>
public enum WorkRisk
{
    /// <summary>
    /// The work is considered low risk.
    /// </summary>
    Low,

    /// <summary>
    /// The work is considered medium risk.
    /// </summary>
    Medium,

    /// <summary>
    /// The work is considered high risk.
    /// </summary>
    High,
}
